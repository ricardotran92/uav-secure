"""Export the current parameters and the model/parameter history to docs/.

Writes
  docs/parameters.json   resolved values of both profiles, with provenance and tested alternatives
  docs/PARAMETERS.md     the same as a highlighted table, for review and tuning
  docs/MODEL_HISTORY.md  architecture, timeline of changes, result snapshots, open issues

The history itself lives in docs/history.json (hand-maintained); everything about the
*current* configuration is read from the YAML files, so it cannot drift from the code.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from uavsec.config import DEFAULT_CONFIG, REPO_ROOT, Config, load_config

DOCS = REPO_ROOT / "docs"
CALIBRATED = REPO_ROOT / "configs" / "calibrated.yaml"

# Values printed in Table I / Sec. VI of the paper (everything else is an assumption or implementation detail).
PAPER_VALUES = {
    "system.area_size": 200.0, "system.num_users": 8, "system.num_antennas": 8, "system.uav_altitude": 100.0,
    "system.rician_factor_db": 10.0, "system.bandwidth_hz": 1.0, "system.power_max_w": 1.0,
    "system.noise_power_w": 1.2e-13, "system.path_loss_a_db": 30.0, "system.path_loss_b": 22.0,
    "system.eve_distance": 20.0,
    "gnn.num_layers": 5, "gnn.lr": 0.005, "gnn.epochs": 300, "gnn.batch_size": 512,
    "sac.lr": 0.0003, "sac.episodes": 500, "sac.batch_size": 64, "sac.buffer_size": 1_000_000, "sac.gamma": 0.99,
}
TAGS = {
    "paper": ("🟢", "PAPER", "value printed in the paper"),
    "assumption": ("🟡", "ASSUMPTION", "paper silent; our choice"),
    "calibrated": ("🔴", "CALIBRATED", "interpretation chosen to reproduce Fig. 7/8; differs from the 'standard' reading"),
    "implementation": ("⚪", "IMPLEMENTATION", "engineering setting, not part of the paper's model"),
}


def flatten(cfg: Config) -> dict[str, object]:
    return {f"{sec}.{k}": v for sec, vals in cfg.to_dict().items() if isinstance(vals, dict) for k, v in vals.items()} | {
        k: v for k, v in cfg.to_dict().items() if not isinstance(v, dict)}


def yaml_comments(path: Path) -> dict[str, str]:
    """Map 'section.key' -> trailing comment of a (two-level) YAML file."""
    out, section = {}, ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if re.match(r"^\w[\w]*:\s*(#.*)?$", line):
            section = line.split(":")[0]
            continue
        m = re.match(r"^(\s*)(\w+):\s*(.*?)(?:\s+#\s*(.*))?$", line)
        if m and m.group(4) is not None:
            indent, key = len(m.group(1)), m.group(2)
            out[f"{section}.{key}" if indent else key] = m.group(4)
    return out


def classify(key: str, value: object, overrides: set[str], comments: dict[str, str]) -> str:
    if key in overrides:
        return "calibrated"
    if key in PAPER_VALUES:
        return "paper"
    return "assumption" if "assumption" in comments.get(key, "").lower() else "implementation"


def build_profile(paths: list[Path]) -> list[dict]:
    cfg = load_config(paths)
    default_cfg = load_config([DEFAULT_CONFIG])
    comments = yaml_comments(DEFAULT_CONFIG)
    overrides = set()
    for p in paths[1:]:
        data = yaml.safe_load(p.read_text(encoding="utf-8"))
        overrides |= {f"{sec}.{k}" for sec, vals in data.items() if isinstance(vals, dict) for k in vals}
    resolved, base = flatten(cfg), flatten(default_cfg)
    rows = []
    for key, value in resolved.items():
        kind = classify(key, value, overrides, comments)
        row = {"key": key, "value": value, "source": kind, "note": comments.get(key, "")}
        if key in PAPER_VALUES:
            row["paper_value"] = PAPER_VALUES[key]
            row["matches_paper"] = bool(value == PAPER_VALUES[key])
        if key in overrides:
            row["default_value"] = base[key]
        rows.append(row)
    return rows


def fmt(v: object) -> str:
    return f"`{v:g}`" if isinstance(v, float) else f"`{v}`"


def esc(text: object) -> str:
    """Make free text safe inside a markdown table cell."""
    return str(text).replace("|", "\|")


def parameters_md(profiles: dict[str, list[dict]], knobs: list[dict]) -> str:
    out = ["# Current parameters", "",
           "Generated by `python scripts/export_docs.py` from the YAML files; do not edit by hand.", "",
           "| Marker | Meaning |", "|---|---|"]
    out += [f"| {icon} **{name}** | {desc} |" for icon, name, desc in TAGS.values()]
    main = profiles["main"]
    counts = {k: sum(r["source"] == k for r in main) for k in TAGS}
    out += ["", f"Main profile: {counts['paper']} paper values, {counts['calibrated']} calibrated, "
                f"{counts['assumption']} assumptions, {counts['implementation']} implementation settings.", "",
            "## Needs attention first (calibrated + assumptions)", "",
            "| | Key | Current | Note | Default / paper |", "|---|---|---|---|---|"]
    for r in main:
        if r["source"] in ("calibrated", "assumption"):
            ref = (f"default `{r['default_value']}`" if "default_value" in r else "")
            out.append(f"| {TAGS[r['source']][0]} | **`{r['key']}`** | **{fmt(r['value'])}** | {esc(r['note'])} | {ref} |")
    out += ["", "## Tuning knobs and what was tried", "", "| Key | Why it matters | Tried |", "|---|---|---|"]
    for k in knobs:
        tried = "<br>".join(f"`{t['value']}`: {esc(t['outcome'])}" for t in k["tested"])
        nxt = f"<br>*Next idea: {k['next_idea']}*" if k.get("next_idea") else ""
        out.append(f"| `{k['key']}` | {esc(k['why'])} | {tried}{nxt} |")
    for title, rows in (("Main profile (calibrated), all parameters", main),
                        ("Reference profile (Table I as printed), differences only",
                         [r for r, m in zip(profiles["reference"], main) if r["value"] != m["value"]])):
        out += ["", f"## {title}", "", "| | Key | Value | Paper |", "|---|---|---|---|"]
        for r in rows:
            paper = ""
            if "paper_value" in r:
                paper = f"{fmt(r['paper_value'])} " + ("✓" if r["matches_paper"] else "✗")
            out.append(f"| {TAGS[r['source']][0]} | `{r['key']}` | {fmt(r['value'])} | {paper} |")
    return "\n".join(out) + "\n"


STATUS = {"match": "✅ match", "close": "🟡 close", "gap": "⚠️ gap"}


FIGURE_ORDER = ("fig4", "fig5", "fig6", "fig7_optimum", "fig7_sac", "fig8", "fig9a", "fig9b", "fig9c", "fig10")
LB_STATUS = {"current": "⭐ current", "ablation": "🔬 ablation", "archived": "📦 archived",
             "rejected": "✖ rejected", "reference": "📏 reference", "alternative": "🔁 alternative"}


def top_results_md(h: dict) -> list[str]:
    """Leaderboard of scored snapshots and the best snapshot per figure."""
    board = h.get("leaderboard")
    if not board:
        return []
    snaps = {s["id"]: s for s in h["results_snapshots"]}
    cards = {e["id"]: e.get("scorecard") or snaps.get(e["id"], {}).get("scorecard") for e in board}
    out = ["## 🏆 Top results", "",
           "Paper-match score from `scripts/paper_scorecard.py` (weighted error over Figs. 4-10, lower = closer "
           "to the paper).", "", "| Rank | Snapshot | Score | Status | What | Location |", "|---|---|---|---|---|---|"]
    for rank, e in enumerate(sorted(board, key=lambda e: e["total"]), 1):
        name = f"**{e['id']}**" if e["status"] == "current" else e["id"]
        out.append(f"| {rank} | {name} | **{e['total']:.3f}** | {LB_STATUS[e['status']]} | {esc(e['label'])} | "
                   f"`{e['location']}` |")
    current = next(e["id"] for e in board if e["status"] == "current")
    out += ["", "**Best snapshot per figure** (excluding the Table I reference):", "",
            "| Figure | Best | Error | Current (" + current + ") |", "|---|---|---|---|"]
    for fig in FIGURE_ORDER:
        scored = [(c[fig], sid) for sid, c in cards.items() if c and fig in c and sid != "R8"]
        if not scored:
            continue
        err, sid = min(scored)
        cur = cards.get(current, {}).get(fig)
        best = f"**{sid}**" if sid == current else sid
        out.append(f"| {fig} | {best} | {err:.3f} | {cur:.3f} |" if cur is not None else f"| {fig} | {best} | {err:.3f} | - |")
    notes = [e for e in board if e.get("note")]
    out += [""] + [f"- {e['id']}: {e['note']}" for e in notes] + [""]
    return out


SCREEN_COLS = (  # key, header, better ("min" | "max"), format
    ("fig9ab_err", "9a+9b error", "min", "{:.3f}"), ("fig9a_err", "9a error", "min", "{:.3f}"),
    ("fig9b_err", "9b error", "min", "{:.3f}"), ("gnn_k8_over_opt", "GNN/OPT K=8", "max", "{:.2f}"),
    ("gnn_k8", "GNN K=8", "max", "{:.2f}"), ("gnn_k1", "GNN K=1", "max", "{:.2f}"),
    ("gnn_40dbm", "GNN 40 dBm", "max", "{:.1f}"), ("fig7_distance_m", "Fig. 7 (m)", "min", "{:.1f}"),
)
MEDALS = ("🥇", "🥈", "🥉")


def screening_md(h: dict) -> list[str]:
    """GNN screening variants of every round in one table, ranked by the Fig. 9a+9b GNN-curve error."""
    rows = h.get("screening")
    if not rows:
        return []
    paper = h.get("screening_paper", {})
    out = ["## 🔬 Screening experiments (top results)", "",
           "GNN variants screened with `scripts/server/screen_gnn.sh` (3 training seeds each, means; Fig. 7 = median). "
           "Errors use the scorecard formula on the GNN curves of Fig. 9a/9b only (lower = closer to the paper); "
           "the best value of each column is bold. The full-run score of a snapshot is in the table above.", "",
           "| Rank | Round | Variant | Changes | " + " | ".join(c[1] for c in SCREEN_COLS) + " |",
           "|---|---|---|---|" + "---|" * len(SCREEN_COLS)]
    best = {}
    for key, _, better, _ in SCREEN_COLS:
        vals = [r[key] for r in rows if r.get(key) is not None]
        best[key] = (min if better == "min" else max)(vals) if vals else None
    for rank, r in enumerate(sorted(rows, key=lambda r: r["fig9ab_err"]), 1):
        cells = []
        for key, _, _, f in SCREEN_COLS:
            v = r.get(key)
            cells.append("-" if v is None else (f"**{f.format(v)}**" if v == best[key] else f.format(v)))
        medal = MEDALS[rank - 1] + " " if rank <= len(MEDALS) else ""
        out.append(f"| {medal}{rank} | {r['round']} | {esc(r['variant'])} | {esc(r['changes'])} | "
                   + " | ".join(cells) + " |")
    if paper:
        out.append("| | | **paper** | | " + " | ".join(
            (f.format(paper[k]) if k in paper else "") for k, _, _, f in SCREEN_COLS) + " |")
    return out + [""]


def highlights_md(h: dict) -> list[str]:
    """'Paper vs ours' table for the current best snapshot, shown right under the title."""
    hl = h.get("highlights")
    if not hl:
        return []
    counts = {k: sum(i["status"] == k for i in hl["items"]) for k in STATUS}
    out = [f"## ⭐ Highlights: paper vs ours (snapshot {hl['snapshot']}, current best)", "",
           f"**{counts['match']} match · {counts['close']} close · {counts['gap']} gap.** {hl['note']}", "",
           "| Figure | Metric | Paper | Ours | Status |", "|---|---|---|---|---|"]
    order = list(STATUS)
    for i in sorted(hl["items"], key=lambda i: order.index(i["status"])):
        ours = f"**{i['ours']}**" if i["status"] == "match" else i["ours"]
        out.append(f"| {i['figure']} | {esc(i['metric'])} | {esc(i['paper'])} | {esc(ours)} | {STATUS[i['status']]} |")
    return out + [""]


def history_md(h: dict, main: list[dict]) -> str:
    out = [f"# Model and parameter history", "", f"_{h['meta']['project']}_  ", f"Updated {h['meta']['updated']}.", "",
           f"- **Main profile:** {h['meta']['main_profile']}",
           f"- **Reference profile:** {h['meta']['reference_profile']}",
           "- Current parameters with provenance markers: [PARAMETERS.md](PARAMETERS.md) (machine-readable: "
           "[parameters.json](parameters.json)). Source of this history: [history.json](history.json).", ""]
    out += top_results_md(h)
    out += screening_md(h)
    out += highlights_md(h)
    out += ["## 1. Architecture", "", "| Block | What it does | Paper |", "|---|---|---|"]
    out += [f"| **{b['block']}** | {esc(b['description'])} | {esc(b['paper'])} |" for b in h["architecture"]]

    out += ["", "## 2. Current state at a glance", "", "**Calibrated / assumed parameters in use:**", ""]
    for r in main:
        if r["source"] in ("calibrated", "assumption"):
            out.append(f"- {TAGS[r['source']][0]} `{r['key']}` = **{fmt(r['value'])}** - {r['note']}")
    snap = h["results_snapshots"][[s["label"].startswith("FINAL main") for s in h["results_snapshots"]].index(True)]
    dep = snap["deployment"]
    out += ["", "**Main-profile results:**", "",
            f"- GNN {snap['convergence']['gnn_val']} vs MLP {snap['convergence']['mlp_val']} bps/Hz (validation).",
            f"- K=8, 1 W: GNN {snap['beamforming_K8_1W']['GNN']} / OPT {snap['beamforming_K8_1W']['OPT']} / "
            f"MLP {snap['beamforming_K8_1W']['MLP']} bps/Hz (GNN = {snap['gnn_over_opt']['K=8']:.0%} of OPT).",
            f"- Fig. 7 optimum {tuple(dep['optimum_gnn'])} vs paper {tuple(dep['paper_optimum'])}: "
            f"**{dep['optimum_distance_to_paper_m']} m**; SAC ends {dep['sac_to_optimum_m']} m from the optimum.",
            f"- Graph-DRL reaches {dep['graph_drl_vs_optimum_pct']}% of the optimum, "
            f"{dep['graph_drl_gain_over_best_heuristic_pct']:+.0f}% over the best heuristic.", ""]

    out += ["## 3. Timeline of changes", "",
            "| ID | Area | Change | Status |", "|---|---|---|---|"]
    badge = {"active": "✅ active", "reverted": "↩️ reverted", "superseded": "⏭️ superseded", "rejected": "✖ rejected"}
    out += [f"| {c['id']} | {c['area']} | {esc(c['title'])} | {badge[c['status']]} |" for c in h["changes"]]
    for c in h["changes"]:
        out += ["", f"### {c['id']} - {c['title']}  ·  {badge[c['status']]}", "",
                f"- **Before:** {c['before']}", f"- **After:** {c['after']}", f"- **Why:** {c['reason']}",
                f"- **Evidence:** {c['evidence']}"]
        if c.get("impact_on_results"):
            out.append(f"- **Impact:** {c['impact_on_results']}")
        if c.get("commits"):
            out.append("- **Commits:** " + ", ".join(f"`{x}`" for x in c["commits"]))

    out += ["", "## 4. Result snapshots", ""]
    current = (h.get("highlights") or {}).get("snapshot")
    for s in h["results_snapshots"]:
        title = f"### {s['id']} - {s['label']}"
        if s["id"] == current:
            title = f"### ⭐ CURRENT BEST - {s['id']} - {s['label']}"
        out += [title, "", "```json", json.dumps({k: v for k, v in s.items()
                                                                           if k not in ("id", "label")}, indent=2), "```", ""]
    out += ["## 5. Open issues", ""] + [f"- {i}" for i in h["open_issues"]]
    return "\n".join(out) + "\n"


def main() -> None:
    history = json.loads((DOCS / "history.json").read_text(encoding="utf-8"))
    profiles = {"main": build_profile([DEFAULT_CONFIG, CALIBRATED]), "reference": build_profile([DEFAULT_CONFIG])}
    (DOCS / "parameters.json").write_text(json.dumps(
        {"legend": {k: {"marker": v[0], "name": v[1], "meaning": v[2]} for k, v in TAGS.items()},
         "profiles": {"main (calibrated)": profiles["main"], "reference (Table I as printed)": profiles["reference"]},
         "tuning_knobs": history["tuning_knobs"]}, indent=2), encoding="utf-8")
    (DOCS / "PARAMETERS.md").write_text(parameters_md(profiles, history["tuning_knobs"]), encoding="utf-8")
    (DOCS / "MODEL_HISTORY.md").write_text(history_md(history, profiles["main"]), encoding="utf-8")
    for name in ("parameters.json", "PARAMETERS.md", "MODEL_HISTORY.md"):
        print("written:", DOCS / name)


if __name__ == "__main__":
    main()
